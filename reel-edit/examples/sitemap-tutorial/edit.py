# ---- the real sitemap.xml, laid out the way a browser shows it ----
XML = (FOLDER / 'unemployedhusein-sitemap.xml').read_text(encoding='utf-8')


def xml_lines():
    lines, depth = [], 0
    for raw in re.findall(r'<[^>]+>[^<]*(?:</[^>]+>)?', XML):
        raw = raw.strip()
        if raw.startswith('<?'):
            continue
        closing = raw.startswith('</')
        if closing:
            depth -= 1
        lines.append(('  ' * depth + raw, '<loc>' in raw))
        if not closing and not raw.endswith('/>') and '</' not in raw:
            depth += 1
    return lines


def sitemap_view(mark_locs):
    # Clearer (his note, 2 Nov 2026): bigger type, browser colours, the first three pages only.
    rows = []
    for text, is_loc in xml_lines()[:19]:
        t = html.escape(text).replace(' ', '&nbsp;')
        t = re.sub(r'(&lt;/?[\w:]+)', r'<span style="color:#881280">\1</span>', t)
        t = re.sub(r'([\w:]+)=(&quot;[^&]*&quot;)', r'<span style="color:#994500">\1</span>=<span style="color:#1A1AA6">\2</span>', t)
        loc = mark_locs and is_loc
        style = f'background:{YELLOW};font-weight:700;' if loc else ''
        rows.append(f'<div style="{style}white-space:nowrap;padding:0 10px;border-radius:8px;width:fit-content">{t}</div>')
    body = (f'<div style="padding:30px 34px;{MONO};font-size:33px;line-height:46px;color:{INK};overflow:hidden;height:100%">'
            f'{"".join(rows)}</div>')
    return full(f'<div style="position:absolute;left:{SAFE_L}px;top:376px">'
                f'{browser(body, url="unemployedhusein.com/sitemap.xml", w=SAFE_W, h=940)}</div>', grid=False)


